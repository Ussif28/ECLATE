import pandas as pd
from openpyxl import load_workbook
from openpyxl.styles import Font, PatternFill, Alignment

def prepare_frequent_itemsets_report(
    frequent_itemsets,
    transactions_count
):
    df = pd.DataFrame(frequent_itemsets)

    df["Itemset"] = df["itemset"].apply(
        lambda items: ", ".join(items)
    )

    df["Itemset Size"] = df["itemset"].apply(len)

    df["Support %"] = (
        df["support_count"] / transactions_count
    ) * 100

    df = df.rename(columns={
        "support_count": "Support Count"
    })

    df = df[[
        "Itemset",
        "Itemset Size",
        "Support Count",
        "Support %"
    ]]

    df = df.sort_values(
        by="Support %",
        ascending=False
    )

    return df

def prepare_association_rules_report(
    association_rules,
    transactions_count
):
    df = pd.DataFrame(association_rules)

    df["Antecedent"] = df["antecedent"].apply(
        lambda items: ", ".join(items)
    )

    df["Consequent"] = df["consequent"].apply(
        lambda items: ", ".join(items)
    )

    df["Support %"] = (
        df["support_count"] / transactions_count
    ) * 100

    df["Confidence %"] = df["confidence"] * 100

    df = df.rename(columns={
        "lift": "Lift"
    })

    df = df[[
        "Antecedent",
        "Consequent",
        "Support %",
        "Confidence %",
        "Lift"
    ]]

    df = df.sort_values(
        by="Confidence %",
        ascending=False
    )

    return df

def prepare_strong_rules_report(
    rules_df,
    min_support_percent,
    min_confidence_percent
):
    strong_rules_df = rules_df[
        (rules_df["Support %"] >= min_support_percent) &
        (rules_df["Confidence %"] >= min_confidence_percent)
    ].copy()

    return strong_rules_df

def export_eclat_report(
    itemsets_df,
    rules_df,
    strong_rules_df,
    output_file="ECLAT_Report.xlsx"
):
    with pd.ExcelWriter(
        output_file,
        engine="openpyxl"
    ) as writer:

        itemsets_df.to_excel(
            writer,
            sheet_name="Frequent Itemsets",
            index=False
        )

        rules_df.to_excel(
            writer,
            sheet_name="Association Rules",
            index=False
        )

        strong_rules_df.to_excel(
            writer,
            sheet_name="Strong Rules",
            index=False
        )

    wb = load_workbook(output_file)

    for ws in wb.worksheets:

        # Format column headers
        for cell in ws[1]:
            cell.font = Font(bold=True, color="FFFFFF")
            cell.fill = PatternFill(
                fill_type="solid",
                fgColor="1F4E78"
            )

        # Adjust column widths
        for column_cells in ws.columns:
            max_length = 0
            column_letter = column_cells[0].column_letter

            for cell in column_cells:
                if cell.value is not None:
                    max_length = max(
                        max_length,
                        len(str(cell.value))
                    )

            ws.column_dimensions[column_letter].width = max_length + 3

    wb.save(output_file)

    return output_file